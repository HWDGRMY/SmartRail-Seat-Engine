"""引擎参数（可调权重）。

所有 Tier 0-5 的惩罚/奖励权重集中在此，便于做敏感性分析与论文复现。
默认值严格对应 README 第 4.1 节的量级。
"""

from __future__ import annotations

from dataclasses import asdict, dataclass


@dataclass
class EngineConfig:
    """多目标代价函数的权重配置。"""

    # -- Tier 0：灾难级 ---------------------------------------------------
    t0_separated_care_bond: float = -100_000.0   # 儿童/需照护人员与同行成人完全分离
    t0_wheelchair_no_accessible: float = -100_000.0  # 轮椅分配至无无障碍车厢
    t0_pregnant_no_companion: float = -100_000.0     # 孕晚期无同行人

    # -- Tier 1：极度糟糕 -------------------------------------------------
    t1_vulnerable_cross_carriage: float = -10_000.0
    t1_care_unit_split_carriage: float = -10_000.0
    t1_conflict_isolation: float = -10_000.0      # 特殊群体被塞进静音车厢
    # 照护绑定"同车厢但未紧邻"：够得到，但需要起身走动。刻意保持为**轻量**惩罚，
    # 因为真正的灾难（跨车厢）已由 Tier 0 拦截；这里若罚得过重，会反向逼迫系统
    # 把带娃家庭拆到两排去"换一个相邻位"，属于本末倒置。
    t1_care_bond_same_carriage: float = -60.0
    # 需照护者两旁没有任何支持人（例如被困在三人座中间位）：属于安全底线问题，
    # 必须重到足以压过"中间座/靠窗的舒适度奖励"，否则求解器会用舒适度换安全。
    t1_isolated_care_member: float = -3_500.0

    # -- Tier 2：很差 -----------------------------------------------------
    t2_adult_cross_carriage: float = -3_000.0

    # -- Tier 3：高权重排斥（动态） ---------------------------------------
    t3_quiet_family_base: float = -2_500.0     # 带娃家庭进静音车厢（按排斥权重缩放）
    t3_quiet_group_extra: float = -800.0       # 每多一位同行人进入静音车厢的额外惩罚
    t3_quiet_blocked_credit: float = -5_000.0  # 静音信用分 < 60 仍被分到静音车厢
    t3_accessible_misuse: float = -15.0
    """**非轮椅旅客占用无障碍专区**的机会成本（Tier 3）。

    这个值来自一次被用户当场发现的真实缺陷：该字段原为 ``0.0``（等于完全不惩罚），
    于是并发模拟里"情侣 / 带娃家庭 / 视障旅客"等普通订单把专区 10 个座位
    吃掉了 **6 个**，导致后到的**轮椅旅客反而无座可安排** ——
    在空车、862 个空座的情况下整单拒票。

    量级选择有讲究：

    * 必须**高于**普通旅客能从专区得到的任何好处。专区座位本身没有额外奖励，
      只有"近车门"等 +20 级设施奖励，因此 −15 已足以让普通旅客优先选普通座位；
    * 必须**远低于** Tier 1/2 的结构性惩罚（−3000 起），
      以免为了避开专区而把一家人拆到不同车厢 —— 那是更严重的问题。
    """

    # -- Tier 4：轻量 -----------------------------------------------------
    t4_aisle_separated: float = -10.0   # 成人同行人被过道分隔
    t4_not_together: float = -30.0      # 静默型同行人未同排

    # -- Tier 5：满足 -----------------------------------------------------
    # 注意量级：奖励只用于"在若干等价约束满足方案之间做最后一层偏好排序"，
    # 绝不允许抵消任何一级惩罚（|最大奖励| << 最小惩罚 |Tier 4| = 10）。
    t5_quiet_solo_adult: float = 50.0       # 普通成人单人旅客主动进静音车厢
    b5_facility_match: float = 20.0         # 精准匹配设施偏好（过道/近门/近卫生间）
    b5_accessible_match: float = 40.0       # 无障碍专区与轮椅用户匹配
    b5_companion_together: float = 30.0     # 同行人相邻
    b5_child_adjacent: float = 50.0         # 需照护者与绑定人紧邻（安全底线加成）
    # 单人奖励硬上限：奖励只用于"在等价方案之间做偏好排序"。任何乘客的奖励
    # 总额都被钳制在此值，保证永远无法翻转最低一级惩罚（Tier 4 = 10 分），
    # 这是"约束优先于偏好"这一设计原则的机器可验证不变量。
    max_reward_per_passenger: float = 60.0

    # -- 空间代价参数 -----------------------------------------------------
    # 下面这组参数都是**真正生效**的（早期版本曾出现"声明但从未读取"的假参数）：
    aisle_crossing_weight: float = 2.0   # 跨越过道的通道代价（单位：排），影响 Seat.manhattan_to
    near_door_rows: int = 3              # 距车门多少排以内视为"近车门"
    near_toilet_rows: int = 3            # 距卫生间多少排以内视为"近卫生间"
    # 单人设施奖励的**下限**：奖励低于该阈值时不再发放。
    # 作用是把"多个小奖励叠加"压回"只在真正匹配时奖励"，避免奖励碎片化。
    min_floor_reward: float = 10.0

    # -- 降级 / 求解器 ----------------------------------------------------
    default_exactness_budget: float = 12.0         # 精确求解器时间预算 (ms)
    max_branch_nodes: int = 60_000
    # 超过该人数的大团体订单直接使用贪心解：候选组合爆炸，精确搜索投入产出比极低。
    max_exact_order_size: int = 8
    greedy_time_budget_ms: float = 80.0
    """**贪心求解的时间上限**（毫秒）。

    这条必须有，原因是一个真实的生产级缺陷：`assign_greedy` 原先**没有时间上限**，
    它对每个候选组合都要跑一次乘客指派评估，而大单元（8 人）的候选池可达
    数十万个组合。实测"一张单 4 位轮椅 + 4 位家属"会让求解**无限期卡死** ——
    不是慢，是永远不返回，整条出票链路被一单堵死（HTTP 请求直接超时）。

    预算耗尽时返回"当前已找到的最好结果"，而不是放弃或报错：
    有部分结果好过没有结果，缺失的人自然进入候补并生成提示。
    """
    max_wheelchairs_per_order: int = 2
    """单张订单允许的最大轮椅旅客人数。

    为什么会需要这条：无障碍专区只有 10 座，而 `zone_quota_ratio = 0.5`
    已经规定"单张订单最多占用专区一半"。让一张订单里塞 4 位轮椅旅客，
    既会把专区吃光（后续轮椅旅客无座），又会让"轮椅进专区 + 家属同车厢"
    的组合枚举规模爆炸（实测直接卡死）。

    运营上也站不住：真实场景里多位轮椅旅客是**分别下单**的（各自有陪同人），
    不会四个人凑一张订单。因此超过该人数时直接判定"无法满足"并建议拆分订单，
    比让用户等一个不确定的结果更负责任。
    """
    # -- 出票策略（"出票优先于座位理想度"）--------------------------------
    # 运营口径：**能出票就出票**。相邻、同排这类"偏好"不满足时，正确做法是照常
    # 出票 + 明确告知旅客"上车后可找列车员现场调剂"，而不是拒票。
    # 拒票（候补）只应发生在"确实没有任何空座"这一种情况下。
    waitlist_wheelchair_without_accessible: bool = False
    """无障碍专区售罄时，轮椅旅客是否拒票候补。

    默认 **False（出票）**：发给普通座位 + 生成 `accessible_zone_full` 提示，
    请站车协助。只有把它设为 True 才会退回"绝不发放普通座位"的保守策略
    —— 该策略会直接损失客票收入，因此不再是默认值。
    """
    prefer_adjacent_for_weak_bonds: bool = True
    """启用**就近梯度**：同行人无法紧邻时，优先"同排 > 隔一排 > 同车厢远排"。

    没有这一项时，代价函数对"同车厢但隔了 10 排"和"同车厢隔 1 排"给同样的
    −30 分，求解器就没有动力把一家人往一起凑（实测会把三人分散到 3 排）。
    """
    b5_near_row_together: float = 20.0
    """STRONG 绑定的"同排（相隔 ≤2 座）"奖励：介于紧邻（+30）与未同排（−30）之间。"""
    b5_same_carriage_adjacent_row: float = 5.0
    """STRONG 绑定的"相邻排"奖励：让"隔一排"优于"隔很多排"。"""

    # -- 同订单默认同座（产品常识）----------------------------------------
    same_order_default_bond: bool = True
    """同一订单内未显式声明关系的乘客，是否默认按"同行人"处理。

    默认 **True**。理由是最朴素的产品常识：**没人会跟陌生人拼一个订单买票**。
    一个订单里的乘客天然是相互认识的，因此"尽量坐到一起"应当是默认行为，
    而不是需要用户额外勾选的选项。

    早期实现把未声明的组合当作 SOFT（弱绑定），结果是同一订单的人被当作
    "互不相识的散客"处理，可能被分散到不同车厢 —— 这既不符合直觉，
    也浪费了"同单必然同行"这一免费信息。

    需要"虽然同一订单但不必坐一起"（例如公司代订、多人各自出差）时，
    调用方可显式传 ``same_order_bond="soft"`` 或 ``"none"`` 覆盖。
    """
    same_order_bond_level: str = "strong"
    """默认绑定的强度：``strong``（同行人，尽量同排相邻）或 ``mandatory``（必须相邻）。

    默认取 ``strong`` 而非 ``mandatory``：现实中"同一订单必须紧邻"过强，
    三四人团体在 2+2 布局下很难满足；``strong`` 已能保证"优先坐一起 +
    跨车厢重罚"，同时保留必要的灵活性。
    """

    # -- V3.0 强化学习奖励整形 -------------------------------------------
    # 这些权重只影响**训练信号**，不改变线上代价函数（affinity）的口径：
    # 学习型策略最终仍以 affinity 与 Tier 0 计数被评估，保证三个版本可比。
    #
    # 量级说明（踩过的坑，共三次迭代）：
    #   1) 亲和度在 ±10^4 量级，直接当奖励会让 PPO 的价值损失飙到 1e9，完全不收敛；
    #   2) 改成 ×0.001 后又退化成"把所有乘客都候补掉"（既不违规也不扣分）；
    #   3) 最终方案：亲和度按"每位乘客参考量级"归一化 + 就座固定正奖励，
    #      且**候补惩罚必须重于任何座位亲和度差异**，否则退化解会重新出现。
    rl_affinity_scale: float = 1.0        # 增量亲和度的整体权重
    rl_affinity_reference: float = 200.0  # 每位乘客的亲和度参考量级（奖励归一化用）
    rl_seat_bonus: float = 4.0            # 成功安置一位乘客的固定奖励（就座优先）
    rl_waitlist_penalty: float = -10.0    # 任何一位乘客被候补的惩罚（重于座位亲和度差异）
    rl_tier0_penalty: float = -10.0       # 每一条 Tier 0 违规的终止惩罚
    rl_isolation_penalty: float = -3.0    # 需照护者被孤立的额外惩罚

    def to_dict(self) -> dict[str, float]:
        return {k: v for k, v in asdict(self).items() if isinstance(v, (int, float))}


DEFAULT_CONFIG = EngineConfig()
